"""
Testing Hook
------------
Monkey-patch Repo.update to automatically schedule test stages:
- After all non-test tasks are done -> create Integration Tests task and run it
- After Integration done -> run E2E
- After E2E done -> run Performance + Security
This keeps orchestration simple & tenant-safe without heavy router edits.
"""

from __future__ import annotations

import logging
from typing import List

from ai_org_backend.agents.e2e import e2e_task
from ai_org_backend.agents.integration import integration_task
from ai_org_backend.agents.performance import performance_task
from ai_org_backend.agents.security import security_task
from ai_org_backend.db import SessionLocal
from ai_org_backend.main import Repo as _Repo
from ai_org_backend.models import Task, TaskDependency

_orig_update = _Repo.update

SPECIAL = {
    "product requirements document",
    "architecture blueprint",
    "architecture & domain review",
    "initialize repository scaffolding",
    "integration tests",
    "e2e & acceptance tests",
    "performance tests",
    "security scan",
}


def _create_task(tenant_id: str, purpose_id: str, desc: str, owner: str) -> Task:
    with SessionLocal() as s:
        t = Task(
            tenant_id=tenant_id,
            purpose_id=purpose_id,
            description=desc,
            business_value=0.0,
            tokens_plan=0,
            purpose_relevance=1.0,
            status="todo",
            owner=owner,
            notes="auto-generated by testing hook",
        )
        s.add(t)
        s.commit()
        s.refresh(t)
        return t


def _depends_on_all_non_special(target_id: str, purpose_id: str) -> None:
    """Wire dependencies: every non-special task -> target (idempotent)."""
    with SessionLocal() as s:
        all_tasks: List[Task] = s.query(Task).filter(Task.purpose_id == purpose_id).all()
        for t in all_tasks:
            if t.id == target_id:
                continue
            if (t.description or "").strip().lower() in SPECIAL:
                continue
            # Does edge exist?
            exists = (
                s.query(TaskDependency)
                .filter(TaskDependency.from_id == t.id, TaskDependency.to_id == target_id)
                .first()
            )
            if not exists:
                s.add(TaskDependency(from_id=t.id, to_id=target_id))
        s.commit()


def _all_non_test_done(purpose_id: str) -> bool:
    with SessionLocal() as s:
        tasks: List[Task] = s.query(Task).filter(Task.purpose_id == purpose_id).all()
        for t in tasks:
            d = (t.description or "").strip().lower()
            if d in SPECIAL:
                continue
            if str(t.status) != "done":
                return False
        return True


def _maybe_schedule_tests(changed_task_id: str) -> None:
    with SessionLocal() as s:
        changed = s.get(Task, changed_task_id)
        if not changed or str(changed.status) != "done":
            return
        tenant_id = changed.tenant_id
        purpose_id = changed.purpose_id

        # Check which testing tasks exist / status
        tasks = s.query(Task).filter(Task.purpose_id == purpose_id).all()
        by_desc = {(t.description or "").strip().lower(): t for t in tasks}

        it = by_desc.get("integration tests")
        e2e = by_desc.get("e2e & acceptance tests")
        perf = by_desc.get("performance tests")
        sec = by_desc.get("security scan")

        # Stage 1: When all non-test tasks done -> create/run Integration
        if _all_non_test_done(purpose_id) and (
            it is None or str(it.status) not in {"todo", "running", "done", "failed"}
        ):
            it = _create_task(tenant_id, purpose_id, "Integration Tests", owner="QA-Integration")
            _depends_on_all_non_special(it.id, purpose_id)
            try:
                integration_task.delay(tenant_id, it.id)
                logging.info("[TestsHook] Started Integration Tests for purpose=%s", purpose_id)
            except Exception as e:
                logging.error("[TestsHook] Cannot enqueue integration: %s", e)
            return  # wait for next update

        # Stage 2: After Integration done -> run E2E
        if it and str(it.status) == "done":
            if e2e is None:
                e2e = _create_task(tenant_id, purpose_id, "E2E & Acceptance Tests", owner="QA-E2E")
                # Depend e2e on integration
                exists = (
                    s.query(TaskDependency)
                    .filter(TaskDependency.from_id == it.id, TaskDependency.to_id == e2e.id)
                    .first()
                )
                if not exists:
                    s.add(TaskDependency(from_id=it.id, to_id=e2e.id))
                    s.commit()
            if str(e2e.status) == "todo":
                try:
                    e2e_task.delay(tenant_id, e2e.id)
                    logging.info("[TestsHook] Started E2E for purpose=%s", purpose_id)
                except Exception as e:
                    logging.error("[TestsHook] Cannot enqueue e2e: %s", e)
            return

        # Stage 3: After E2E done -> run Perf + Security
        if e2e and str(e2e.status) == "done":
            if perf is None:
                perf = _create_task(tenant_id, purpose_id, "Performance Tests", owner="QA-Perf")
                s.add(TaskDependency(from_id=e2e.id, to_id=perf.id))
                s.commit()
            if sec is None:
                sec = _create_task(tenant_id, purpose_id, "Security Scan", owner="QA-Sec")
                s.add(TaskDependency(from_id=e2e.id, to_id=sec.id))
                s.commit()
            if str(perf.status) == "todo":
                try:
                    performance_task.delay(tenant_id, perf.id)
                    logging.info("[TestsHook] Started Perf for purpose=%s", purpose_id)
                except Exception as e:
                    logging.error("[TestsHook] Cannot enqueue perf: %s", e)
            if str(sec.status) == "todo":
                try:
                    security_task.delay(tenant_id, sec.id)
                    logging.info("[TestsHook] Started Security for purpose=%s", purpose_id)
                except Exception as e:
                    logging.error("[TestsHook] Cannot enqueue security: %s", e)


def update_with_tests(self, task_id: str, **fields):
    """Wrap Repo.update to observe state transitions and schedule testing stages."""
    res = _orig_update(self, task_id, **fields)
    try:
        if "status" in fields and str(fields["status"]) == "done":
            _maybe_schedule_tests(task_id)
    except Exception as e:
        logging.error("[TestsHook] scheduling failed: %s", e)
    return res


# Activate patch
_Repo.update = update_with_tests
